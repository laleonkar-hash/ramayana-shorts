CX = "iw/2-(iw/zoom/2)"
CY = "ih/2-(ih/zoom/2)"


def motion(name, n):
    """zoompan (z, x, y) expressions. n = number of frames in the clip."""
    n = max(n - 1, 1)
    table = {
        "zoom_in":   ("min(1.0+0.0010*on,1.28)", CX, CY),
        "zoom_out":  ("max(1.28-0.0010*on,1.0)", CX, CY),
        "pan_left":  ("1.18", f"(iw-iw/zoom)*(1-on/{n})", CY),
        "pan_right": ("1.18", f"(iw-iw/zoom)*(on/{n})", CY),
        "pan_up":    ("1.18", CX, f"(ih-ih/zoom)*(1-on/{n})"),
        "pan_down":  ("1.18", CX, f"(ih-ih/zoom)*(on/{n})"),
        "shake":     ("1.10+0.0005*on", f"{CX}+sin(on*2.3)*18*max(0,1-on/30)", f"{CY}+cos(on*2.9)*18*max(0,1-on/30)"),
        "punch":     ("1.0+0.20*min(on/5,1)+0.0006*on", CX, CY),
    }
    return table.get(name, table["zoom_in"])


def run(cmd, cwd=None):
    p = subprocess.run(cmd, cwd=cwd, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True)
    if p.returncode != 0:
        raise RuntimeError("ffmpeg failed:\n" + p.stderr[-1800:])


