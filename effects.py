def make_sfx(name, outdir):
    path = f"sfx_{name}.wav"
    if not os.path.exists(os.path.join(outdir, path)):
        run(["ffmpeg", "-y", "-f", "lavfi", "-i", SFX[name], "-ar", "44100", "-ac", "2", path], outdir)
    return path


def make_drone(outdir, seconds):
    """Soft tanpura-like devotional drone (Sa-Pa-Sa) generated by FFmpeg."""
    path = "drone.wav"
    expr = ("0.30*sin(2*PI*130.81*t)+0.26*sin(2*PI*131.40*t)+0.22*sin(2*PI*196.00*t)"
            "+0.20*sin(2*PI*261.63*t)+0.10*sin(2*PI*392.00*t)+0.06*sin(2*PI*523.25*t)")
    run(["ffmpeg", "-y", "-f", "lavfi", "-i", f"aevalsrc='{expr}':d={seconds:.2f}:s=44100",
         "-af", "tremolo=f=0.35:d=0.35,lowpass=f=1500,aecho=0.8:0.6:90|180:0.35|0.2,"
                f"afade=t=in:d=1.5,afade=t=out:st={max(seconds - 2.0, 0):.2f}:d=2.0",
         "-ac", "2", path], outdir)
    return path


# ------------------------------------------------------------------ ASS captions
def _ass_time(t):
    t = max(t, 0.0)
    h, m, s = int(t // 3600), int(t % 3600 // 60), t % 60
    return f"{h}:{m:02d}:{s:05.2f}"


def _bgr(rgb):
    return f"&H00{rgb[4:6]}{rgb[2:4]}{rgb[0:2]}&"


def chunks(text, max_words=5):
    """Short caption chunks: break after punctuation or every few words."""
    out, cur = [], []
    for w in text.split():
        cur.append(w)
        ends = w[-1] in ".?!,"
        if len(cur) >= max_words or (ends and len(cur) >= 2):
            out.append(cur)
            cur = []
    if cur:
        if out and len(cur) == 1:
            out[-1] += cur
        else:
            out.append(cur)
    return [" ".join(c) for c in out]


def _display(chunk):
    return re.sub(r"[.,]+$", "", chunk).replace("{", "").replace("}", "")


def build_ass(scenes, episode_number):
    W, H, font = config.WIDTH, config.HEIGHT, config.CAPTION_FONT
    total = sum(s["dur"] + config.SCENE_PAD for s in scenes)
    head = f"""[Script Info]
ScriptType: v4.00+
PlayResX: {W}
PlayResY: {H}
WrapStyle: 0
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Cap,{font},78,&H00FFFFFF,&H00FFFFFF,&H00000000,&H96000000,-1,0,0,0,100,100,0,0,1,7,2,2,80,80,300,1
Style: Badge,{font},44,&H0000123A,&H0000123A,&H0028AAFF,&H0028AAFF,-1,0,0,0,100,100,1,0,3,14,0,8,60,60,118,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    lines = [f"Dialogue: 0,{_ass_time(0)},{_ass_time(total)},Badge,,0,0,0,,रामायण • भाग {episode_number}"]
    offset = 0.0
    for sc in scenes:
        color = _bgr(cast.VOICES[sc["profile"]][3])
        parts = chunks(sc["text"])
        weights = [max(len(p), 4) for p in parts]
        t = offset
        for part, wgt in zip(parts, weights):
            d = sc["dur"] * wgt / sum(weights)
            pop = r"{\fscx88\fscy88\t(0,110,\fscx100\fscy100)\c" + color + "}"
            lines.append(f"Dialogue: 1,{_ass_time(t)},{_ass_time(t + d)},Cap,,0,0,0,,{pop}{_display(part)}")
            t += d
        offset += sc["dur"] + config.SCENE_PAD
    return head + "\n".join(lines) + "\n"
